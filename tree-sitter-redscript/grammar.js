/// <reference types="tree-sitter-cli/dsl" />
// Based on crates/syntax/community/parser; syntax support, not semantic validation.
const commaSep1 = rule => seq(rule, repeat(seq(',', rule)));
const commaSep = rule => optional(seq(commaSep1(rule), optional(',')));
const binary = [
  [3, ['||']], [4, ['&&']], [5, ['|']], [6, ['^']], [7, ['&']],
  [8, ['==', '!=']], [9, ['<', '<=', '>', '>=']],
  [10, ['+', '-']], [11, ['*', '/', '%']],
];

module.exports = grammar({
  name: 'redscript',
  extras: $ => [/\s/, $.line_comment, $.block_comment],
  externals: $ => [$.block_comment, $.string_content],
  word: $ => $.identifier,
  conflicts: $ => [
    [$.named_type, $.expression], [$.lambda_parameter, $.expression],
    [$.unary_expression, $.binary_expression, $.call_expression],
    [$.binary_expression, $.call_expression], [$.named_type],
    [$.function_type, $.lambda_parameters], [$.named_type, $.lambda_parameter],
    [$.named_type, $.expression, $.lambda_parameter], [$.path],
  ],

  rules: {
    source_file: $ => seq(optional($.module_declaration), repeat($.declaration)),
    module_declaration: $ => seq('module', $.path),
    path: $ => seq($.identifier, repeat(seq('.', $.identifier))),
    declaration: $ => seq(repeat($.annotation), optional($.visibility), repeat($.qualifier),
      choice($.import_declaration, $.class_declaration, $.struct_declaration,
        $.enum_declaration, $.function_declaration, $.field_declaration, $.default_declaration)),
    visibility: _ => choice('public', 'private', 'protected'),
    qualifier: _ => choice('abstract', 'cb', 'const', 'editable', 'exec', 'final',
      'importonly', 'instanceeditable', 'inlined', 'native', 'persistent', 'quest',
      'replicated', 'static', 'testonly'),
    annotation: $ => seq('@', field('name', $.identifier), $.value_arguments),
    import_declaration: $ => seq('import', $.path,
      optional(seq('.', choice('*', seq('{', commaSep($.identifier), '}')))), optional(';')),
    class_declaration: $ => seq('class', field('name', $.identifier), optional($.type_parameters),
      optional(seq('extends', field('supertype', $.type))), $.declaration_body, optional(';')),
    struct_declaration: $ => seq('struct', field('name', $.identifier), optional($.type_parameters),
      optional(seq('extends', field('supertype', $.type))), $.declaration_body, optional(';')),
    declaration_body: $ => seq('{', repeat($.declaration), '}'),
    enum_declaration: $ => seq('enum', field('name', $.identifier),
      optional(seq(':', field('storage', $.type))), '{', commaSep($.enum_variant), '}', optional(';')),
    enum_variant: $ => seq(field('name', $._extended_identifier),
      optional(seq('=', optional('-'), $.integer_literal))),
    function_declaration: $ => prec.right(seq(optional(choice('explicit', 'implicit')), 'func',
      field('name', choice($.identifier, $.operator_name)), optional($.type_parameters), $.parameters,
      optional(seq('->', optional('const'), field('return_type', $.type))),
      optional(choice(field('body', $.block), seq('=', field('body', $.expression)))), optional(';'))),
    operator_name: _ => seq('operator', '[', ']'),
    parameters: $ => seq('(', commaSep($.parameter), ')'),
    parameter: $ => seq(repeat($.parameter_qualifier), field('name', $._parameter_name), ':', field('type', $.type)),
        _parameter_name: $ => choice($.identifier, alias(choice('opt', 'out', 'const', 'skip'), $.identifier)),
    parameter_qualifier: _ => choice('opt', 'out', 'const', 'skip'),
    field_declaration: $ => seq('let', field('name', $._extended_identifier), ':', field('type', $.type),
      optional(seq('=', field('value', $.expression))), ';'),
    default_declaration: $ => seq('default', field('target', $._extended_identifier), '=', $.expression, ';'),
    _extended_identifier: $ => choice($.identifier, alias(choice('true', 'false', 'default'), $.identifier)),

    type_parameters: $ => seq('<', optional(commaSep1($.type_parameter)), '>'),
    type_parameter: $ => seq(optional(field('variance', choice('+', '-'))), field('name', $.identifier),
      optional(seq('extends', field('bound', $.type)))),
    type: $ => choice($.named_type, $.array_type, $.function_type),
    named_type: $ => seq(field('name', $.identifier), optional($.type_arguments)),
    type_arguments: $ => seq('<', optional(commaSep1($.type)), '>'),
    call_type_arguments: $ => seq('<', commaSep($.type), '>'),
    array_type: $ => seq('[', field('element', $.type), optional(seq(';', field('size', $.integer_literal))), ']'),
    function_type: $ => prec.right(seq('(', optional(commaSep1($.type)), ')', '->', field('return_type', $.type))),

    block: $ => seq('{', repeat($._statement), '}'),
    _statement: $ => choice($.local_declaration, $.expression_statement, $.if_statement,
      $.while_statement, $.for_statement, $.switch_statement, $.return_statement,
      $.break_statement, $.continue_statement),
    local_declaration: $ => seq(choice('let', 'const'), field('name', $.identifier),
      optional(seq(':', field('type', $.type))), optional(seq('=', field('value', $.expression))), ';'),
    expression_statement: $ => seq($.expression, ';'),
    if_statement: $ => seq('if', $.condition, field('consequence', $.block),
      repeat(seq('else', 'if', $.condition, $.block)), optional(seq('else', field('alternative', $.block))), optional(';')),
    condition: $ => choice($.expression, seq('let', $.pattern, '=', $.expression)),
    while_statement: $ => seq('while', $.condition, $.block, optional(';')),
    for_statement: $ => seq('for', field('name', $.identifier), 'in', $.expression, $.block, optional(';')),
    switch_statement: $ => seq('switch', $.expression, '{', repeat($.switch_section), '}', optional(';')),
    switch_section: $ => seq(choice(seq('case', choice($.expression, seq('let', $.pattern))), 'default'),
      ':', repeat($._statement)),
    return_statement: $ => seq('return', optional($.expression), ';'),
    break_statement: _ => seq('break', ';'),
    continue_statement: _ => seq('continue', ';'),
    pattern: $ => choice($.identifier, $.aggregate_pattern, $.array_pattern, $.as_pattern, $.nullable_pattern),
    aggregate_pattern: $ => seq(field('name', $.identifier), '{', commaSep($.field_pattern), '}'),
    field_pattern: $ => seq(field('name', $._extended_identifier), optional(seq(':', $.pattern))),
    array_pattern: $ => seq('[', choice(
      commaSep($.pattern),
      seq($.spread_pattern, optional(seq(',', commaSep1($.pattern))), optional(',')),
      seq(commaSep1($.pattern), ',', $.spread_pattern, optional(','))), ']'),
    spread_pattern: _ => seq('.', '.'),
    as_pattern: $ => prec.left(seq($.pattern, 'as', $.type)),
    nullable_pattern: $ => prec.left(seq($.pattern, '?')),

    expression: $ => choice($.identifier, $.integer_literal, $.float_literal, $.string_literal,
      $.cname_literal, $.resource_literal, $.tweakdbid_literal, $.interpolated_string,
      $.boolean_literal, $.null_literal, $.this_expression, $.super_expression,
      $.array_literal, $.parenthesized_expression, $.new_expression, $.lambda_expression,
      $.dynamic_cast_expression, $.unary_expression, $.binary_expression, $.assignment_expression,
      $.conditional_expression, $.call_expression, $.member_expression, $.index_expression),
    parenthesized_expression: $ => seq('(', $.expression, ')'),
    array_literal: $ => seq('[', commaSep($.expression), ']'),
    new_expression: $ => prec(15, seq('new', field('type', $.type), $.value_arguments)),
    lambda_expression: $ => prec.right(seq($.lambda_parameters, '->', field('body', choice($.block, $.expression)))),
    lambda_parameters: $ => seq('(', commaSep($.lambda_parameter), ')'),
    lambda_parameter: $ => seq(field('name', $.identifier), optional(seq(':', field('type', $.type)))),
    dynamic_cast_expression: $ => prec.left(12, seq(field('value', $.expression), 'as', field('type', $.type))),
    unary_expression: $ => prec.right(13, seq(field('operator', choice('-', '!', '~')), field('operand', $.expression))),
    binary_expression: $ => choice(...binary.map(([precedence, operators]) =>
      prec.left(precedence, seq(field('left', $.expression), field('operator', operators.length === 1 ? operators[0] : choice(...operators)), field('right', $.expression))))),
    assignment_expression: $ => prec.right(0, seq(field('left', $.expression),
      field('operator', choice('=', '+=', '-=', '*=', '/=', '|=', '&=')), field('right', $.expression))),
    conditional_expression: $ => prec.right(1, seq(field('condition', $.expression), '?',
      field('consequence', $.expression), ':', field('alternative', $.expression))),
    // The community parser tries a generic call before comparison operators.
    call_expression: $ => prec.dynamic(1, prec.left(15,
      seq(field('function', $.expression), optional($.call_type_arguments), $.arguments))),
    // Unlike constructor and annotation arguments, call slots may be omitted.
    arguments: $ => seq('(', optional($.expression), repeat(seq(',', optional($.expression))), ')'),
    value_arguments: $ => seq('(', commaSep($.expression), ')'),
    member_expression: $ => prec.left(15, seq(field('object', $.expression), '.', field('member', $._extended_identifier))),
    index_expression: $ => prec.left(15, seq(field('object', $.expression), '[', field('index', $.expression), ']')),

    identifier: _ => /[A-Za-z_][A-Za-z_0-9]*/,
    integer_literal: _ => /(?:0|[1-9][0-9]*)(?:ul|u|l)?/,
    float_literal: _ => token(choice(
      /(?:0|[1-9][0-9]*)\.[0-9]*(?:[eE][+-]?[0-9]+)?d?/,
      /(?:0|[1-9][0-9]*)(?:[eE][+-]?[0-9]+)?d/)),
    string_literal: $ => seq('"', repeat(choice($.string_content, $.escape_sequence)), '"'),
    cname_literal: $ => seq('n"', repeat(choice($.string_content, $.escape_sequence)), '"'),
    resource_literal: $ => seq('r"', repeat(choice($.string_content, $.escape_sequence)), '"'),
    tweakdbid_literal: $ => seq('t"', repeat(choice($.string_content, $.escape_sequence)), '"'),
    interpolated_string: $ => seq('s"', repeat(choice($.string_content, $.escape_sequence, $.interpolation)), '"'),

    escape_sequence: _ => token.immediate(/\\(?:[nrt'"\\]|u\{[0-9a-fA-F]{1,6}\})/),
    interpolation: $ => seq(token.immediate('\\('), $.expression, ')'),
    boolean_literal: _ => choice('true', 'false'),
    null_literal: _ => 'null',
    this_expression: _ => 'this',
    super_expression: _ => 'super',
    line_comment: _ => token(seq('//', /[^\r\n\v\f\u0085\u2028\u2029]*/)),
  },
});
