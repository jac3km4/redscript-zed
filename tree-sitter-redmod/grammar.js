/// <reference types="tree-sitter-cli/dsl" />
// Syntax-oriented subset of crates/syntax/redmod/parser, not a semantic validator.
const commaSep1 = rule => seq(rule, repeat(seq(',', rule)));
const commaSep = rule => optional(seq(commaSep1(rule), optional(',')));
const binary = [
  [3, ['||']], [4, ['&&']], [5, ['|']], [6, ['^']], [7, ['&']],
  [8, ['==', '!=']], [9, ['<', '<=', '>', '>=']],
  [10, ['+', '-']], [11, ['*', '/', '%']],
];

module.exports = grammar({
  name: 'redmod',
  extras: $ => [/\s/, $.line_comment, $.block_comment],
  externals: $ => [$.block_comment],
  word: $ => $.identifier,
  conflicts: $ => [[$.type, $.expression]],

  rules: {
    source_file: $ => repeat(choice($.module_directive, $.using_directive, $.declaration)),
    module_directive: $ => seq('@', 'module', $.string_literal, optional(';')),
    using_directive: $ => seq('@', 'using', $.string_literal, optional(';')),
    declaration: $ => seq(
      repeat($.metadata), repeat($.annotation), repeat($.qualifier),
      choice($.class_declaration, $.struct_declaration, $.enum_declaration,
        $.function_declaration, $.variable_declaration, $.property_directive),
    ),
    qualifier: _ => choice('public', 'private', 'protected', 'abstract', 'const',
      'exec', 'final', 'importonly', 'import', 'persistent', 'quest', 'static',
      'editable', 'instanceeditable', 'inlined', 'replicated', 'testonly',
      'override', 'export', 'virtual', 'constexpr', 'mutable'),
    metadata: $ => seq('[', commaSep1($.metadata_entry), ']'),
    metadata_entry: $ => seq(field('key', $.identifier), '=', field('value', $.expression)),
    annotation: $ => seq('@', field('name', $.identifier), $.arguments),
    class_declaration: $ => seq('class', field('name', $.identifier),
      optional(seq('extends', field('supertype', $.type))), $.declaration_body, optional(';')),
    struct_declaration: $ => seq('struct', field('name', $.identifier),
      optional(seq('extends', field('supertype', $.type))), $.declaration_body, optional(';')),
    declaration_body: $ => seq('{', repeat($.declaration), '}'),
    enum_declaration: $ => seq('enum', field('name', $.identifier),
      optional(seq(':', field('storage', $.type))), '{', commaSep($.enum_variant), '}', optional(';')),
    enum_variant: $ => seq(field('name', $.identifier), optional(seq('=', optional('-'), $.number_literal))),
    function_declaration: $ => seq(
      choice(seq(choice('function', 'event'), field('name', $.identifier)),
        seq('operator', field('name', $.operator_name)), seq(optional('implicit'), 'cast')),
      $.parameters, optional(seq(choice(':', '->'), optional('const'), field('return_type', $.type))),
      optional(field('body', $.block)), optional(';')),
    operator_name: _ => choice('+', '-', '*', '/', '%', '==', '!=', '<', '<=', '>', '>=',
      '&&', '||', '&', '|', '^', '!', '~', '+=', '-=', '*=', '/=', '&=', '|=', seq('[', ']')),
    parameters: $ => seq('(', commaSep($.parameter), ')'),
    parameter: $ => seq(repeat($.parameter_qualifier), commaSep1(field('name', $.identifier)), ':', field('type', $.type)),
    parameter_qualifier: _ => choice('optional', 'out', 'const', 'skip'),
    variable_declaration: $ => seq($._variable, ';'),
    _variable: $ => seq(choice('var', 'let'), commaSep1(field('name', $.identifier)),
      ':', field('type', $.type), optional(seq('=', field('value', $.expression)))),
    property_directive: $ => seq(choice('default', 'hint'), field('target', $.identifier), '=', $.expression, ';'),
    type: $ => prec.right(seq(field('name', $.identifier), optional($.type_arguments), repeat($.array_size))),
    type_arguments: $ => seq('<', commaSep1($.type), '>'),
    array_size: $ => seq('[', $.number_literal, ']'),

    block: $ => seq('{', repeat($._statement), '}'),
    _statement: $ => choice($.block, $.local_declaration, $.expression_statement,
      $.if_statement, $.while_statement, $.do_statement, $.for_statement,
      $.switch_statement, $.return_statement, $.break_statement, $.continue_statement, $.empty_statement),
    local_declaration: $ => seq(optional('const'), $._variable, ';'),
    expression_statement: $ => seq($.expression_list, ';'),
    expression_list: $ => commaSep1($.expression),
    if_statement: $ => seq('if', $.condition, field('consequence', $.block),
      optional(seq('else', field('alternative', choice($.block, $.if_statement))))),
    condition: $ => seq('(', $.expression, ')'),
    while_statement: $ => seq('while', $.condition, $.block),
    do_statement: $ => seq('do', $.block, 'while', $.condition, ';'),
    for_statement: $ => seq('for', '(', optional(field('initializer', choice(
      seq(optional('const'), $._variable), $.expression_list))), ';',
      optional(field('condition', $.expression_list)), ';',
      optional(field('update', $.expression_list)), ')', $.block),
    switch_statement: $ => seq('switch', $.condition, '{', repeat($.switch_section), '}'),
    switch_section: $ => seq(choice(seq('case', $.expression), 'default'), ':', repeat($._statement)),
    return_statement: $ => seq('return', optional($.expression), ';'),
    break_statement: _ => seq('break', ';'),
    continue_statement: _ => seq('continue', ';'),
    empty_statement: _ => ';',

    expression: $ => choice($.identifier, $.number_literal, $.string_literal, $.cname_literal,
      $.resource_literal, $.tweakdbid_literal, $.boolean_literal, $.null_literal, $.this_expression,
      $.super_expression, $.array_literal, $.parenthesized_expression, $.new_expression,
      $.cast_expression, $.dynamic_cast_expression, $.unary_expression, $.binary_expression,
      $.assignment_expression, $.conditional_expression, $.call_expression,
      $.member_expression, $.index_expression),
    parenthesized_expression: $ => seq('(', $.expression, ')'),
    array_literal: $ => seq('[', commaSep($.expression), ']'),
    new_expression: $ => prec(14, seq('new', field('type', $.type))),
    // Prefer casts to grouped identifiers in (T)(x) and (T)-x.
    cast_expression: $ => choice(
      prec(15, seq('Cast', '<', field('type', $.type), '>', '(', field('value', $.expression), ')')),
      prec.right(13, prec.dynamic(1, seq('(', field('type', $.type), ')', field('value', $.expression))))),
    dynamic_cast_expression: $ => prec.left(12, seq(field('value', $.expression), 'as', field('type', $.type))),
    unary_expression: $ => prec.right(13, seq(field('operator', choice('-', '!', '~')), field('operand', $.expression))),
    binary_expression: $ => choice(...binary.map(([precedence, operators]) =>
      prec.left(precedence, seq(field('left', $.expression), field('operator', operators.length === 1 ? operators[0] : choice(...operators)), field('right', $.expression))))),
    assignment_expression: $ => prec.right(0, seq(field('left', $.expression),
      field('operator', choice('=', '+=', '-=', '*=', '/=', '|=', '&=')), field('right', $.expression))),
    conditional_expression: $ => prec.right(1, seq(field('condition', $.expression), '?',
      field('consequence', $.expression), ':', field('alternative', $.expression))),
    call_expression: $ => prec.left(15, seq(field('function', $.expression), $.arguments)),
    // Slots can be omitted, including leading/trailing slots.
    arguments: $ => seq('(', optional($.expression), repeat(seq(',', optional($.expression))), ')'),
    member_expression: $ => prec.left(15, seq(field('object', $.expression), '.', field('member', $.identifier))),
    index_expression: $ => prec.left(15, seq(field('object', $.expression), '[', field('index', $.expression), ']')),
    identifier: _ => /[A-Za-z_][A-Za-z_0-9]*/,
    number_literal: _ => /(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[eE][+-]?[0-9]+)?[fld]?/,
    // Backslashes are ordinary characters; a quote always ends the literal.
    string_literal: _ => token(seq('"', /[^"]*/, '"')),
    cname_literal: _ => token(choice(seq("'", /[^']*/, "'"), seq('n"', /[^"]*/, '"'))),
    resource_literal: _ => token(seq('R"', /[^"]*/, '"')),
    tweakdbid_literal: _ => token(seq('T"', /[^"]*/, '"')),
    boolean_literal: _ => choice('true', 'false'),
    null_literal: _ => 'NULL',
    this_expression: _ => 'this',
    super_expression: _ => 'super',
    line_comment: _ => token(seq('//', /[^\r\n\v\f\u0085\u2028\u2029]*/)),
  },
});
